import { describe, it, expect } from "vitest";
import { gelWords } from "./gel-words.js";

describe("gelWords", () => {
  const cases: [number, string][] = [
    [0, "ნული"],
    [5, "ხუთი"],
    [10, "ათი"],
    [15, "თხუთმეტი"],
    [20, "ოცი"],
    [21, "ოცდაერთი"],
    [30, "ოცდაათი"],
    [35, "ოცდათხუთმეტი"],
    [50, "ორმოცდაათი"],
    [70, "სამოცდაათი"],
    [90, "ოთხმოცდაათი"],
    [99, "ოთხმოცდაცხრამეტი"],
    [100, "ასი"],
    [105, "ას ხუთი"],
    [150, "ას ორმოცდაათი"],
    [235, "ორას ოცდათხუთმეტი"],
    [500, "ხუთასი"],
    [800, "რვაასი"],
    [1000, "ათასი"],
    [1200, "ათას ორასი"],
    [1500, "ათას ხუთასი"],
    [2000, "ორი ათასი"],
    [2500, "ორი ათას ხუთასი"],
    [5000, "ხუთი ათასი"],
  ];
  for (const [n, want] of cases) {
    it(`${n} → ${want}`, () => {
      expect(gelWords(n)).toBe(want);
    });
  }
});
